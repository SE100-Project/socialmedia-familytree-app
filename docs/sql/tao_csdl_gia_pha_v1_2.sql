  doi_tuong VARCHAR(100) NOT NULL,
  doi_tuong_id BIGINT NOT NULL,
  truoc JSONB, sau JSONB,
  nguoi_thuc_hien_id BIGINT REFERENCES tai_khoan(id) ON DELETE SET NULL,
